export function insideCoast(x: number, z: number, ring: CoastPoint[]) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, zi] = ring[i],
      [xj, zj] = ring[j];
    if (zi > z !== zj > z && x < ((xj - xi) * (z - zi)) / (zj - zi) + xi)
      inside = !inside;
  }
  return inside;
}

export function isRegionalGround(
  id: RegionId,
  x: number,
  z: number,
  margin = 0,
) {
  const test = (px: number, pz: number) =>
    insideCoast(px, pz, regionalTerrain[id].coast) &&
    (id !== "sumatera-utara" || !insideCoast(px, pz, batakLake));
  return (
    test(x, z) &&
    (!margin ||
      [
        [margin, 0],
        [-margin, 0],
        [0, margin],
        [0, -margin],
      ].every(([dx, dz]) => test(x + dx, z + dz)))
  );
}
